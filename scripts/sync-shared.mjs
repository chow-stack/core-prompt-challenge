// Copies shared/scoring.ts into the Edge Functions bundle (Supabase deploys each function folder plus _shared only).
// Run after editing shared/scoring.ts: node scripts/sync-shared.mjs. tests/scoring.test.ts fails if the copy drifts.
import { readFileSync, writeFileSync } from "node:fs";

const HEADER = "// GENERATED by scripts/sync-shared.mjs from shared/scoring.ts. Do not edit here.\n";
const src = readFileSync(new URL("../shared/scoring.ts", import.meta.url), "utf8");
writeFileSync(new URL("../supabase/functions/_shared/scoring.ts", import.meta.url), HEADER + src);
console.log("Synced supabase/functions/_shared/scoring.ts");
